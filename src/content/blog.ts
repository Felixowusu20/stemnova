/** Retrieve a blog post by slug. */
export function getBlogPostBySlug(slug: string): BlogPost | undefined {
  return blogPosts.find((post) => post.slug === slug);
}

/** Retrieve the n most recent blog posts. */
export function getLatestPosts(n: number): BlogPost[] {
  return [...blogPosts]
    .sort((a, b) => b.publishedAt.localeCompare(a.publishedAt))
    .slice(0, n);
}

/** Retrieve featured blog posts. */
export function getFeaturedPosts(): BlogPost[] {
  return blogPosts.filter((post) => post.featured);
}

/** Retrieve related posts by category, excluding the current post. */
export function getRelatedPosts(
  slug: string,
  limit: number = 3
): BlogPost[] {
  const current = getBlogPostBySlug(slug);
  if (!current) return getLatestPosts(limit);

  return blogPosts
    .filter(
      (post) => post.slug !== slug && post.category === current.category
    )
    .sort((a, b) => b.publishedAt.localeCompare(a.publishedAt))
    .slice(0, limit);
}

/** Filter posts by category. */
export function getPostsByCategory(category: BlogCategory): BlogPost[] {
  return blogPosts
    .filter((post) => post.category === category)
    .sort((a, b) => b.publishedAt.localeCompare(a.publishedAt));
}
